#!/usr/bin/env python3
"""Local preview and export server for the design mockups (standard library only).

Serves the ``design/`` tree on http://localhost:8765 and accepts the write that
``exportSvgFrames(name)`` / ``exportForFigma(name)`` in ``design/system/noop.js`` perform:

    POST /save?name=<file>      body = the frames JSON (or flattened HTML)
        -> design/export/<file>, answered with the byte count as text/plain

The Figma plugin in ``design/figma-plugin`` then fetches
``http://localhost:8765/export/<file>`` (for example ``r6-frames.json``).

Usage, from anywhere:

    python3 design/tools/serve.py                      # serve until Ctrl-C
    python3 design/tools/serve.py --export round6-scorecard/index.html --name r6-frames.json

``--export`` starts the server, opens the page headless with ``?static=1&export=<name>`` (pages that
support it call ``exportSvgFrames`` themselves when they see ``export=``), waits for the file,
checks that it is well-formed, prints a summary and exits. It needs a Chrome or Chromium binary;
pass ``--chrome /path/to/binary`` when none is found automatically.

``design/export/`` is generated output. The server writes a ``.gitignore`` containing ``*`` into it,
so exports never show up in ``git status``. The server binds to 127.0.0.1 only and writes nowhere
except that directory.
"""
import argparse
import glob
import json
import os
import re
import shutil
import subprocess
import sys
import threading
import time
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import parse_qs, urlparse

DESIGN = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXPORT = os.path.join(DESIGN, "export")
SAFE_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,99}$")
MAX_BODY = 64 * 1024 * 1024


def ensure_export_dir():
    os.makedirs(EXPORT, exist_ok=True)
    ignore = os.path.join(EXPORT, ".gitignore")
    if not os.path.exists(ignore):
        with open(ignore, "w", encoding="utf-8") as f:
            f.write("# Generated by design/tools/serve.py. Exported frames are never committed.\n*\n")


class Handler(SimpleHTTPRequestHandler):
    def end_headers(self):
        # The plugin's hidden iframe has a null origin, so the export must be readable cross-origin.
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Cache-Control", "no-store")
        super().end_headers()

    def do_OPTIONS(self):
        self.send_response(204)
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type")
        self.end_headers()

    def reply(self, status, text):
        body = text.encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "text/plain; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_POST(self):
        url = urlparse(self.path)
        if url.path != "/save":
            return self.reply(404, "Only POST /save?name=<file> is supported")
        name = (parse_qs(url.query).get("name") or [""])[0]
        if not SAFE_NAME.match(name):
            return self.reply(400, "name must be a plain file name (letters, digits, . _ -)")
        try:
            length = int(self.headers.get("Content-Length") or "")
        except ValueError:
            return self.reply(411, "Content-Length is required")
        if length < 0 or length > MAX_BODY:
            return self.reply(413, "Body too large")
        data = self.rfile.read(length)
        ensure_export_dir()
        tmp = os.path.join(EXPORT, name + ".part")
        with open(tmp, "wb") as f:
            f.write(data)
        os.replace(tmp, os.path.join(EXPORT, name))
        sys.stderr.write(f"saved export/{name} ({len(data)} bytes)\n")
        self.reply(200, str(len(data)))

    def log_message(self, fmt, *args):
        if os.environ.get("SERVE_VERBOSE"):
            super().log_message(fmt, *args)


def find_chrome(explicit):
    if explicit:
        return explicit
    home = os.path.expanduser("~")
    candidates = sorted(glob.glob(os.path.join(home, "Library/Caches/ms-playwright/chromium_headless_shell-*/chrome-*/chrome-headless-shell")), reverse=True)
    candidates += sorted(glob.glob(os.path.join(home, ".cache/ms-playwright/chromium_headless_shell-*/chrome-*/chrome-headless-shell")), reverse=True)
    candidates += [
        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
        "/Applications/Chromium.app/Contents/MacOS/Chromium",
        "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
    ]
    candidates += [p for p in (shutil.which(n) for n in ("chromium", "chromium-browser", "google-chrome", "chrome")) if p]
    return next((c for c in candidates if os.path.exists(c)), None)


def check_frames(path):
    """Returns (ok, lines). A frames file is a JSON array of {name, w, h, svg, texts[]}."""
    with open(path, encoding="utf-8") as f:
        frames = json.load(f)
    problems, lines, names = [], [], set()
    if not isinstance(frames, list) or not frames:
        return False, ["not a non-empty JSON array"]
    for i, fr in enumerate(frames):
        name = fr.get("name") if isinstance(fr, dict) else None
        if not name or not isinstance(fr.get("svg"), str) or not fr["svg"].startswith("<svg") or not fr["svg"].rstrip().endswith("</svg>"):
            problems.append(f"frame {i}: missing name or svg")
            continue
        if name in names:
            problems.append(f"duplicate frame name: {name}")
        names.add(name)
        if not (fr.get("w", 0) > 0 and fr.get("h", 0) > 0):
            problems.append(f"{name}: bad size")
        texts = fr.get("texts")
        if not isinstance(texts, list):
            problems.append(f"{name}: texts is not a list")
            texts = []
        lines.append(f"  {name}  {fr.get('w')}x{fr.get('h')}  svg {len(fr['svg'])} chars  {len(texts)} text lines")
    return not problems, lines + [f"  PROBLEM: {p}" for p in problems]


def run_export(port, page, name, chrome, window):
    binary = find_chrome(chrome)
    if not binary:
        print("export not executed: no Chrome/Chromium binary found (pass --chrome)")
        return 2
    target = os.path.join(EXPORT, name)
    before = os.path.getmtime(target) if os.path.exists(target) else 0
    url = f"http://localhost:{port}/{page.lstrip('/')}?static=1&export={name}"
    cmd = [binary, "--headless", "--disable-gpu", "--hide-scrollbars", f"--window-size={window}",
           "--virtual-time-budget=20000", "--dump-dom", url]
    print(f"exporting {url}\n  with {binary}")
    proc = subprocess.run(cmd, capture_output=True, text=True, timeout=180)
    deadline = time.time() + 20
    while time.time() < deadline and not (os.path.exists(target) and os.path.getmtime(target) > before):
        time.sleep(0.25)
    if not (os.path.exists(target) and os.path.getmtime(target) > before):
        print("export FAILED: the page did not write the file")
        print(proc.stderr[-2000:])
        return 1
    ok, lines = check_frames(target)
    print(f"export/{name}: {os.path.getsize(target)} bytes, {len([l for l in lines if 'PROBLEM' not in l])} frames")
    print("\n".join(lines))
    print("well-formed" if ok else "NOT well-formed")
    return 0 if ok else 1


def main():
    ap = argparse.ArgumentParser(description="Serve design/ and receive frame exports.")
    ap.add_argument("--port", type=int, default=8765)
    ap.add_argument("--export", metavar="PAGE", help="page under design/ to export headless, then exit")
    ap.add_argument("--name", default="r6-frames.json", help="export file name (default r6-frames.json)")
    ap.add_argument("--chrome", help="Chrome/Chromium binary for --export")
    ap.add_argument("--window", default="4200,9000", help="headless window size for --export")
    args = ap.parse_args()

    ensure_export_dir()
    server = ThreadingHTTPServer(("127.0.0.1", args.port), partial(Handler, directory=DESIGN))
    if args.export:
        threading.Thread(target=server.serve_forever, daemon=True).start()
        code = run_export(args.port, args.export, args.name, args.chrome, args.window)
        server.shutdown()
        sys.exit(code)
    print(f"Serving {DESIGN} on http://localhost:{args.port}  (exports -> design/export/)")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
